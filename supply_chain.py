# ============================================================

def higher_is_better(series):
    if series.max() == series.min():
        return pd.Series(100, index=series.index)

    return (
        (series - series.min()) /
        (series.max() - series.min())
    ) * 100


def lower_is_better(series):
    if series.max() == series.min():
        return pd.Series(100, index=series.index)

    return (
        (series.max() - series) /
        (series.max() - series.min())
    ) * 100


# Higher is better
supplier_performance["On_Time_Score"] = higher_is_better(
    supplier_performance["On_Time_Delivery_%"]
)

supplier_performance["Fulfillment_Score"] = higher_is_better(
    supplier_performance["Quantity_Fulfillment_%"]
)


# Lower is better
supplier_performance["Defect_Score"] = lower_is_better(
    supplier_performance["Defect_Rate_%"]
)

supplier_performance["Lead_Time_Score"] = lower_is_better(
    supplier_performance["Average_Lead_Time_Days"]
)


